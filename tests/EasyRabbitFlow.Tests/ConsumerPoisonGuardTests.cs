using EasyRabbitFlow.Settings;

namespace EasyRabbitFlow.Tests;

public class ConsumerPoisonGuardTests
{
    [Theory]
    [InlineData(5, 5, true)]
    [InlineData(5, 7, true)]
    [InlineData(5, 4, false)]
    [InlineData(1, 1, true)]
    public void GivesUp_OnlyWhenTheBrokerCountReachesTheLimit(int max, int count, bool expected)
    {
        Assert.Equal(expected, ConsumerPoisonGuard.ShouldGiveUp(max, count, redelivered: true, autoAckOnError: false, hasDeadLetterQueue: true));
    }

    [Theory]
    [InlineData(null)]
    [InlineData(0)]
    [InlineData(-1)]
    public void Disabled_WhenTheLimitIsNullOrNonPositive(int? max)
    {
        Assert.False(ConsumerPoisonGuard.ShouldGiveUp(max, 100, redelivered: true, autoAckOnError: false, hasDeadLetterQueue: true));
    }

    [Fact]
    public void Ignored_WithoutABrokerCount()
    {
        // Classic queues never set x-delivery-count: the guard cannot apply there.
        Assert.False(ConsumerPoisonGuard.ShouldGiveUp(5, null, redelivered: true, autoAckOnError: false, hasDeadLetterQueue: true));
    }

    [Fact]
    public void Ignored_OnAFirstDelivery_EvenWithACount()
    {
        // A count on a first delivery is publisher-supplied or left over from a manual replay, not a loop.
        Assert.False(ConsumerPoisonGuard.ShouldGiveUp(5, 20, redelivered: false, autoAckOnError: false, hasDeadLetterQueue: true));
    }

    [Fact]
    public void Ignored_WithAutoAckOnError()
    {
        // Giving up would acknowledge the message unprocessed: silent loss. The handler runs instead.
        Assert.False(ConsumerPoisonGuard.ShouldGiveUp(5, 20, redelivered: true, autoAckOnError: true, hasDeadLetterQueue: true));
    }

    [Fact]
    public void Ignored_WithoutTheAutoGeneratedDeadLetterQueue()
    {
        // Without a DLQ the rejected delivery would be dropped (unless the queue has its own DLX the library cannot see).
        Assert.False(ConsumerPoisonGuard.ShouldGiveUp(5, 20, redelivered: true, autoAckOnError: false, hasDeadLetterQueue: false));
    }
}
